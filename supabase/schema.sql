  on public.students to authenticated;

-- ============================== POLICIES ==============================
-- Standard tables: owner = all; manager + admin = own branch (select/insert/update);
-- manager (not admin) may delete.
do $$
declare t text;
begin
  foreach t in array array['students','student_contacts','leads','lessons','lesson_students',
                           'attendance','progress','requests','announcements'] loop
    execute format($f$create policy %1$s_owner on %1$I for all to authenticated
      using (my_role() = 'owner') with check (my_role() = 'owner')$f$, t);
    execute format($f$create policy %1$s_staff_select on %1$I for select to authenticated
      using (my_role() in ('manager','admin') and branch_id = my_branch())$f$, t);
    execute format($f$create policy %1$s_staff_insert on %1$I for insert to authenticated
      with check (my_role() in ('manager','admin') and branch_id = my_branch())$f$, t);
    execute format($f$create policy %1$s_staff_update on %1$I for update to authenticated
      using (my_role() in ('manager','admin') and branch_id = my_branch())
      with check (my_role() in ('manager','admin') and branch_id = my_branch())$f$, t);
    execute format($f$create policy %1$s_manager_delete on %1$I for delete to authenticated
      using (my_role() = 'manager' and branch_id = my_branch())$f$, t);
  end loop;
end $$;

-- Admin also needs to delete these (convert a lead, edit a lesson's students, un-mark attendance).
create policy leads_admin_delete on leads for delete to authenticated
  using (my_role() = 'admin' and branch_id = my_branch());
create policy lesson_students_admin_delete on lesson_students for delete to authenticated
  using (my_role() = 'admin' and branch_id = my_branch());
create policy attendance_admin_delete on attendance for delete to authenticated
  using (my_role() = 'admin' and branch_id = my_branch());

-- Teacher: own lessons, the students in them, attendance, progress notes. Nothing else.
create policy lessons_teacher_select on lessons for select to authenticated
  using (my_role() = 'teacher' and teacher_id = auth.uid());

create policy lesson_students_teacher_select on lesson_students for select to authenticated
  using (my_role() = 'teacher' and teaches_lesson(lesson_id));

create policy students_teacher_select on students for select to authenticated
  using (my_role() = 'teacher' and teaches_student(id));

create policy attendance_teacher_select on attendance for select to authenticated
  using (my_role() = 'teacher' and teaches_lesson(lesson_id));
create policy attendance_teacher_insert on attendance for insert to authenticated
  with check (my_role() = 'teacher' and teaches_lesson(lesson_id) and branch_id = my_branch());
create policy attendance_teacher_update on attendance for update to authenticated
  using (my_role() = 'teacher' and teaches_lesson(lesson_id))
  with check (my_role() = 'teacher' and teaches_lesson(lesson_id) and branch_id = my_branch());
create policy attendance_teacher_delete on attendance for delete to authenticated
  using (my_role() = 'teacher' and teaches_lesson(lesson_id));

create policy progress_teacher_select on progress for select to authenticated
  using (my_role() = 'teacher' and teaches_student(student_id));
create policy progress_teacher_insert on progress for insert to authenticated
  with check (my_role() = 'teacher' and teaches_student(student_id) and branch_id = my_branch());

-- Announcements are readable by everyone in the branch, including teachers.
create policy announcements_branch_select on announcements for select to authenticated
  using (branch_id = my_branch());

-- Invoices (finance): owner + manager only. Only the owner can delete.
create policy invoices_owner on invoices for all to authenticated
  using (my_role() = 'owner') with check (my_role() = 'owner');
create policy invoices_manager_select on invoices for select to authenticated
  using (my_role() = 'manager' and branch_id = my_branch());
create policy invoices_manager_insert on invoices for insert to authenticated
  with check (my_role() = 'manager' and branch_id = my_branch());
create policy invoices_manager_update on invoices for update to authenticated
  using (my_role() = 'manager' and branch_id = my_branch())
  with check (my_role() = 'manager' and branch_id = my_branch());

-- Extras: admin may use every list except "Recurring invoices" (finance).
create policy extras_owner on extras for all to authenticated
  using (my_role() = 'owner') with check (my_role() = 'owner');
create policy extras_manager on extras for all to authenticated
  using (my_role() = 'manager' and branch_id = my_branch())
  with check (my_role() = 'manager' and branch_id = my_branch());
create policy extras_admin_select on extras for select to authenticated
  using (my_role() = 'admin' and branch_id = my_branch() and type <> 'Recurring invoices');
create policy extras_admin_insert on extras for insert to authenticated
  with check (my_role() = 'admin' and branch_id = my_branch() and type <> 'Recurring invoices');
create policy extras_admin_update on extras for update to authenticated
  using (my_role() = 'admin' and branch_id = my_branch() and type <> 'Recurring invoices')
  with check (my_role() = 'admin' and branch_id = my_branch() and type <> 'Recurring invoices');

-- Branches: owner sees all, everyone else only their own. Owner + manager may edit name/email.
create policy branches_select on branches for select to authenticated
  using (my_role() = 'owner' or id = my_branch());
create policy branches_update on branches for update to authenticated
  using (my_role() = 'owner' or (my_role() = 'manager' and id = my_branch()))
  with check (my_role() = 'owner' or (my_role() = 'manager' and id = my_branch()));

-- Profiles: read-only from the app. You see yourself; owner sees all; manager/admin see their branch's staff.
-- Nobody can change a role from the app.
create policy profiles_self on profiles for select to authenticated
  using (id = auth.uid());
create policy profiles_owner on profiles for select to authenticated
  using (my_role() = 'owner');
create policy profiles_branch on profiles for select to authenticated
  using (my_role() in ('manager','admin') and branch_id = my_branch());
