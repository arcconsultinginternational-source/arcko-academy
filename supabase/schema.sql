-- Arcko Academy Studio · database schema + row-level security (RLS)
-- Run ONCE in Supabase → SQL Editor, on a new empty project.
--
-- Roles
--   owner   : every branch, everything
--   manager : own branch, everything incl. finance (a franchisee = manager of their branch)
--   admin   : own branch, no finance (no invoices, payroll, recurring invoices)
--   teacher : only their own lessons, the students in them, attendance + progress notes;
--             never parent contacts, leads or finance
--
-- Every row carries a branch_id. Foreign keys include branch_id, so a record in one branch
-- can never be linked to a record in another branch, even by a crafted request.

-- ============================== TABLES ==============================
create table branches (
  id bigint generated by default as identity primary key,
  name text not null,
  email text,
  created_at timestamptz not null default now()
);

create table profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null check (role in ('owner','manager','admin','teacher')),
  branch_id bigint references branches(id),
  created_at timestamptz not null default now(),
  check ((role = 'owner') = (branch_id is null)),   -- owner has no branch; everyone else must
  unique (id, branch_id)
);

create table students (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references branches(id),
  name text not null,
  age int check (age between 0 and 120),
  dob date,
  school text,
  subject text not null,
  level text not null default 'Level 1',
  total int not null default 0 check (total >= 0),             -- sessions purchased
  sessions_used int not null default 0 check (sessions_used >= 0),  -- maintained by trigger only
  coins int not null default 0 check (coins >= 0),
  status text not null default 'Active' check (status in ('Active','Archived')),
  note text,
  created_at timestamptz not null default now(),
  unique (id, branch_id)
);

-- Parent contact details live in their own table so teachers can be denied access to them.
create table student_contacts (
  student_id bigint primary key,
  branch_id bigint not null,
  parent text,
  phone text,
  email text,
  foreign key (student_id, branch_id) references students(id, branch_id) on delete cascade
);

create table leads (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references branches(id),
  name text not null,
  child text,
  age int,
  subject text,
  phone text,
  status text not null default 'New inquiry',
  created_at timestamptz not null default now()
);

create table lessons (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references branches(id),
  subject text not null,
  title text not null,
  date date not null,
  time text not null check (time ~ '^[0-9]{2}:[0-9]{2}$'),
  teacher_id uuid,
  room text,
  created_at timestamptz not null default now(),
  unique (id, branch_id),
  foreign key (teacher_id, branch_id) references profiles(id, branch_id) on delete set null (teacher_id)
);

create table lesson_students (
  lesson_id bigint not null,
  student_id bigint not null,
  branch_id bigint not null,
  primary key (lesson_id, student_id),
  unique (lesson_id, student_id, branch_id),
  foreign key (lesson_id, branch_id) references lessons(id, branch_id) on delete cascade,
  foreign key (student_id, branch_id) references students(id, branch_id) on delete cascade
);

-- A row exists only once attendance is marked ("Not marked" = no row).
create table attendance (
  lesson_id bigint not null,
  student_id bigint not null,
  branch_id bigint not null,
  status text not null check (status in ('Present','Absent','Excused')),
  created_at timestamptz not null default now(),
  primary key (lesson_id, student_id),
  foreign key (lesson_id, student_id, branch_id)
    references lesson_students(lesson_id, student_id, branch_id) on delete cascade
);

-- FINANCE: owner + manager only.
create table invoices (
  id bigint generated by default as identity (start with 1001) primary key,
  branch_id bigint not null,
  student_id bigint not null,
  subject text not null,
  amount numeric(12,2) not null check (amount >= 0),
  status text not null default 'Unpaid' check (status in ('Paid','Unpaid')),
  date date not null default current_date,
  due date not null,
  method text,
  created_at timestamptz not null default now(),
  foreign key (student_id, branch_id) references students(id, branch_id) on delete restrict
);

create table progress (
  id bigint generated by default as identity primary key,
  branch_id bigint not null,
  student_id bigint not null,
  subject text,
  date date not null default current_date,
  title text not null,
  body text not null,
  author text,
  created_at timestamptz not null default now(),
  foreign key (student_id, branch_id) references students(id, branch_id) on delete cascade
);

create table requests (   -- make-up requests
  id bigint generated by default as identity primary key,
  branch_id bigint not null,
  student_id bigint not null,
  date date not null,
  time text not null check (time ~ '^[0-9]{2}:[0-9]{2}$'),
  reason text,
  status text not null default 'Pending' check (status in ('Pending','Approved','Declined')),
  created_at timestamptz not null default now(),
  foreign key (student_id, branch_id) references students(id, branch_id) on delete cascade
);

create table announcements (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references branches(id),
  title text not null,
  body text,
  date date not null default current_date,
  created_at timestamptz not null default now()
);

-- Free-form lists: Packages, Schools & venues, Holidays, Recurring invoices (finance only).
create table extras (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references branches(id),
  type text not null check (type in ('Packages','Schools & venues','Holidays','Recurring invoices')),
  name text not null,
  details text,
  created_at timestamptz not null default now()
);

create index on students (branch_id);
create index on leads (branch_id);
create index on lessons (branch_id, date);
create index on lessons (teacher_id);
create index on lesson_students (student_id);
create index on attendance (student_id);
create index on invoices (branch_id);
create index on progress (student_id);
create index on requests (branch_id);

-- ============================== HELPERS ==============================
-- security definer: they read profiles/lessons without triggering RLS on those tables.
create function public.my_role() returns text
  language sql stable security definer set search_path = public
  as $$ select role from profiles where id = auth.uid() $$;

create function public.my_branch() returns bigint
  language sql stable security definer set search_path = public
  as $$ select branch_id from profiles where id = auth.uid() $$;

create function public.teaches_lesson(lid bigint) returns boolean
  language sql stable security definer set search_path = public
  as $$ select exists (select 1 from lessons where id = lid and teacher_id = auth.uid()) $$;

create function public.teaches_student(sid bigint) returns boolean
  language sql stable security definer set search_path = public
  as $$ select exists (
    select 1 from lesson_students ls join lessons l on l.id = ls.lesson_id
    where ls.student_id = sid and l.teacher_id = auth.uid()) $$;

revoke execute on function public.my_role(), public.my_branch(),
  public.teaches_lesson(bigint), public.teaches_student(bigint) from public, anon;
grant execute on function public.my_role(), public.my_branch(),
  public.teaches_lesson(bigint), public.teaches_student(bigint) to authenticated;

-- Keeps students.sessions_used correct no matter who marks attendance, and refuses to
-- mark "Present" when no sessions remain.
create function public.attendance_sync_used() returns trigger
  language plpgsql security definer set search_path = public
  as $$
declare
  delta int := 0;
  sid bigint;
  t int;
  u int;
begin
  if tg_op = 'INSERT' then
    sid := new.student_id;
    if new.status = 'Present' then delta := 1; end if;
  elsif tg_op = 'DELETE' then
    sid := old.student_id;
    if old.status = 'Present' then delta := -1; end if;
  else
    if old.lesson_id <> new.lesson_id or old.student_id <> new.student_id then
      raise exception 'Attendance cannot be moved to another lesson or student';
    end if;
    sid := new.student_id;
    if old.status <> 'Present' and new.status = 'Present' then delta := 1;
    elsif old.status = 'Present' and new.status <> 'Present' then delta := -1;
    end if;
  end if;

  if delta <> 0 then
    update students set sessions_used = sessions_used + delta
      where id = sid
      returning total, sessions_used into t, u;
    if delta > 0 and u > t then
      raise exception 'No sessions remaining. Add a package first.';
    end if;
  end if;
  return coalesce(new, old);
end $$;

create trigger attendance_sync_used
  after insert or update or delete on attendance
  for each row execute function public.attendance_sync_used();

